import AppKit
import CryptoKit
import UniformTypeIdentifiers

/// Polls `NSPasteboard.general.changeCount` and hands new content to the store.
@MainActor
final class PasteboardWatcher {
    private let store: ClipStore
    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?

    private var settings: AppSettings { AppSettings.shared }

    /// Pasteboard markers from http://nspasteboard.org that mean "do not record".
    private static let privateTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    init(store: ClipStore) {
        self.store = store
        self.lastChangeCount = pasteboard.changeCount
    }

    func start() {
        timer?.invalidate()
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.tick() }
        }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func tick() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard !store.isPaused else { return }
        guard let (item, payload) = capture() else { return }
        store.maxItems = settings.maxItems
        store.maxAgeDays = settings.maxAgeDays
        let (id, isNew) = store.insert(item, payload: payload)
        if isNew, item.kind == .image, settings.ocrImages {
            let store = store
            Task {
                if let text = await ImageTextRecognizer.recognize(payload) {
                    store.setOCRText(text, for: id)
                }
            }
        }
    }

    /// Reads the current pasteboard into a ClipItem, or nil when it should be skipped.
    func capture() -> (ClipItem, Data)? {
        guard let types = pasteboard.types, !types.isEmpty else { return nil }
        if types.contains(where: Self.privateTypes.contains) { return nil }

        let frontApp = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        if let frontApp, settings.ignoredApps.contains(frontApp) { return nil }

        // Files first: Finder puts both file URLs and a textual path on the board.
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let paths = urls.map(\.path).joined(separator: "\n")
            return make(kind: .file, uti: UTType.fileURL.identifier, preview: paths, payload: Data(paths.utf8), app: frontApp)
        }
        if types.contains(.png) || types.contains(.tiff) {
            guard settings.captureImages else { return nil }
            guard let data = pasteboard.data(forType: .png) ?? tiffAsPNG() else { return nil }
            guard data.count <= settings.maxImageMB * 1024 * 1024 else { return nil }
            let image = NSImage(data: data)
            let size = image?.size ?? .zero
            let preview = "Image \(Int(size.width))×\(Int(size.height))"
            return make(kind: .image, uti: UTType.png.identifier, preview: preview, payload: data, app: frontApp,
                        thumb: image.flatMap { Self.thumbnailPNG($0, side: 144) })
        }
        if types.contains(.rtf), let rtf = pasteboard.data(forType: .rtf),
           let plain = NSAttributedString(rtf: rtf, documentAttributes: nil)?.string, !plain.isBlank {
            return make(kind: .rtf, uti: UTType.rtf.identifier, preview: String(plain.prefix(200)), payload: rtf, app: frontApp)
        }
        if let string = pasteboard.string(forType: .string), !string.isBlank {
            return make(kind: .text, uti: UTType.utf8PlainText.identifier, preview: String(string.prefix(200)), payload: Data(string.utf8), app: frontApp)
        }
        return nil
    }

    private func tiffAsPNG() -> Data? {
        guard let tiff = pasteboard.data(forType: .tiff),
              let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }

    private func make(kind: ClipKind, uti: String, preview: String, payload: Data, app: String?, thumb: Data? = nil) -> (ClipItem, Data) {
        let item = ClipItem(
            id: 0,
            createdAt: Date(),
            kind: kind,
            uti: uti,
            preview: preview,
            thumb: thumb,
            ocrText: nil,
            byteSize: payload.count,
            contentHash: SHA256.hash(data: payload).map { String(format: "%02x", $0) }.joined(),
            sourceApp: app,
            pinned: false
        )
        return (item, payload)
    }

    /// Small PNG for the row thumbnail, made once at capture so rows never decode the full image.
    static func thumbnailPNG(_ image: NSImage, side: CGFloat) -> Data? {
        let scale = min(side / max(image.size.width, 1), side / max(image.size.height, 1), 1)
        let size = NSSize(width: max(1, image.size.width * scale), height: max(1, image.size.height * scale))
        guard let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: Int(size.width), pixelsHigh: Int(size.height),
                                         bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
                                         colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0) else { return nil }
        NSGraphicsContext.saveGraphicsState()
        NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: rep)
        image.draw(in: NSRect(origin: .zero, size: size), from: .zero, operation: .copy, fraction: 1)
        NSGraphicsContext.restoreGraphicsState()
        return rep.representation(using: .png, properties: [:])
    }
}

extension String {
    var isBlank: Bool { allSatisfy(\.isWhitespace) }
}
